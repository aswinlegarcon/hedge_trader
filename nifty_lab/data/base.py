"""Common market-data types and validation.

Every dataset carries :class:`DataProvenance` so the UI can show *where* the
data came from, *when* it was last updated, and whether it is synthetic.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
from enum import Enum

import pandas as pd

OHLCV_COLUMNS = ["open", "high", "low", "close", "volume"]


class DataKind(str, Enum):
    SYNTHETIC = "SYNTHETIC"          # generated by this app; NOT real market data
    IMPORTED_CSV = "IMPORTED_CSV"    # user-supplied historical file
    BROKER_LIVE = "BROKER_LIVE"      # read-only broker API (Phase 2)
    UNAVAILABLE = "UNAVAILABLE"


@dataclass(frozen=True)
class DataProvenance:
    kind: DataKind
    source: str
    symbol: str
    retrieved_at: datetime
    last_bar_time: datetime | None
    notes: str = ""
    instrument_key: str = ""
    bar_interval: str = ""
    exchange_tz: str = ""

    @property
    def is_synthetic(self) -> bool:
        return self.kind == DataKind.SYNTHETIC

    def freshness_label(self, now: datetime | None = None) -> str:
        """Human-readable staleness relative to the last bar."""
        if self.last_bar_time is None:
            return "NO DATA"
        now = now or datetime.now(timezone.utc)
        last = self.last_bar_time
        if last.tzinfo is None:
            last = last.replace(tzinfo=timezone.utc)
        age = now - last.astimezone(timezone.utc)
        if age.total_seconds() < 3600:
            return f"Last bar {int(age.total_seconds() // 60)} min ago"
        days = age.days
        if days <= 0:
            return "Last bar today"
        if days == 1:
            return "1 day old"
        return f"{days} days old"


@dataclass
class MarketDataset:
    """An OHLCV frame indexed by timestamp plus provenance."""

    df: pd.DataFrame
    provenance: DataProvenance

    def __post_init__(self) -> None:
        self.df = validate_ohlcv(self.df)

    @property
    def last_close(self) -> float:
        return float(self.df["close"].iloc[-1])


class DataValidationError(ValueError):
    pass


def validate_ohlcv(df: pd.DataFrame) -> pd.DataFrame:
    """Validate and normalise an OHLCV frame.

    Requirements: DatetimeIndex (sorted, unique), numeric OHLCV columns,
    high >= max(open, close), low <= min(open, close), no NaNs in OHLC.
    """
    if df is None or len(df) == 0:
        raise DataValidationError("Dataset is empty")
    missing = [c for c in OHLCV_COLUMNS if c not in df.columns]
    if missing:
        raise DataValidationError(f"Missing columns: {missing}. Required: {OHLCV_COLUMNS}")
    out = df.copy()
    if not isinstance(out.index, pd.DatetimeIndex):
        raise DataValidationError("Index must be a DatetimeIndex")
    out = out[~out.index.duplicated(keep="last")].sort_index()
    for c in OHLCV_COLUMNS:
        out[c] = pd.to_numeric(out[c], errors="coerce")
    if out[["open", "high", "low", "close"]].isna().any().any():
        raise DataValidationError("OHLC columns contain non-numeric or missing values")
    out["volume"] = out["volume"].fillna(0.0)
    bad_high = (out["high"] < out[["open", "close"]].max(axis=1)).sum()
    bad_low = (out["low"] > out[["open", "close"]].min(axis=1)).sum()
    if bad_high or bad_low:
        raise DataValidationError(
            f"Inconsistent bars: {int(bad_high)} with high<max(open,close), {int(bad_low)} with low>min(open,close)"
        )
    if (out[["open", "high", "low", "close"]] <= 0).any().any():
        raise DataValidationError("Prices must be positive")
    return out[OHLCV_COLUMNS]
